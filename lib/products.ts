// O(1) lookups by slug; the catalogue is read on every cart render and on every order request.
const bySlug: ReadonlyMap<string, Product> = new Map(products.map((p) => [p.slug, p]));

export function getProduct(slug: string): Product | undefined {
  return bySlug.get(slug);
}

export function related(product: Product, count = 4) {
  const same = products.filter((p) => p.slug !== product.slug && p.category === product.category);
  const others = products.filter((p) => p.slug !== product.slug && p.category !== product.category && p.featured);
  return [...same, ...others].slice(0, count);
}

export const featured = products.filter((p) => p.featured);
